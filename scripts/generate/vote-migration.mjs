/**
 * Mika Creator — vote migration generator
 *
 * Emits supabase/migrations/001_votes_v2.sql for a LIVE v1 database:
 *   - backfills votes.record_key ("<Category>|<index>") -> new object_type/object_id
 *   - drops legacy record_key + constraint, dedupes, tightens uniqueness
 *   - shifts privacy: no anon SELECT on raw votes; safe views only
 *
 * Every mapping is validated against the processed manifest; any unmapped
 * legacy key is reported on stdout here and skipped in SQL.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  ROOT, WORK_DIR, LEGACY_GALLERY_DIR, loadJson, ensureDir,
} from '../lib/fs.mjs';

const META = path.join(WORK_DIR, 'assets-meta.json');
const LEGACY = path.join(LEGACY_GALLERY_DIR, 'data.js.legacy.json');
const OUT = path.join(ROOT, 'supabase', 'migrations', '001_votes_v2.sql');

const slugify = (s) => String(s).toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '');
const quote = (v) => `'` + String(v).replace(/'/g, "''") + `'`;

export function generateVoteMigration() {
  const meta = loadJson(META, { assets: [] });
  const legacy = loadJson(LEGACY, {});
  if (!meta.assets?.length || !Object.keys(legacy).length) throw new Error('need assets-meta.json + data.js.legacy.json');

  const byFile = new Map();
  for (const a of meta.assets) byFile.set(a.file, a);

  const rows = [];
  const unmapped = [];
  const moved = new Set();
  for (const [cat, files] of Object.entries(legacy)) {
    files.forEach((file, i) => {
      const asset = byFile.get(file);
      const recordKey = `${cat}|${i}`;
      if (!asset) { unmapped.push(recordKey); return; }
      if (asset.collection !== slugify(cat)) moved.add(`${recordKey} → ${asset.collection}:${asset.slug}`);
      rows.push({ recordKey, slug: asset.slug });
    });
  }
  if (unmapped.length) {
    console.warn(`unmapped legacy keys: ${unmapped.length}`);
    unmapped.forEach((k) => console.warn('   ' + k));
  }
  if (moved.size) console.log(`legacy keys re-attached to current collection: ${moved.size}`);

  const values = rows.map((r) => `(${quote(r.recordKey)}, 'asset', ${quote(r.slug)})`).join(',\n  ');
  const distinct = rows.length;

  const sql = `-- =====================================================================
-- Mika Creator — migration 001: votes v1 -> v2
-- Generated by scripts/generate/vote-migration.mjs
-- Maps ${distinct} legacy record_keys ("<Category>|<index>") to new
-- object_type='asset' + object_id=<slug>, preserving every historical vote.
--
-- HOW TO RUN (EXISTING v1 project): Dashboard -> SQL Editor -> paste + Run.
-- Afterwards run the (idempotent) parts of supabase/schema.sql for the v2
-- RPCs/comments table — that file is safe to execute against this state.
-- =====================================================================

begin;

-- 1) new columns
alter table public.votes add column if not exists object_type text;
alter table public.votes add column if not exists object_id   text;

-- 2) mapping table
create temp table _legacy_vote_map (
  record_key  text primary key,
  object_type text,
  object_id   text
) on commit drop;
insert into _legacy_vote_map (record_key, object_type, object_id) values
  ${values};

-- 3) backfill (actions preserved; like+switch semantics unchanged)
update public.votes v
set object_type = m.object_type,
    object_id   = m.object_id
from _legacy_vote_map m
where v.record_key = m.record_key;

-- 4) votes pointing at content that no longer exists are dropped
delete from public.votes
where object_id is null or object_type is null;

-- 5) enforce the v2 "one row per visitor per object per action" shape
delete from public.votes a
using public.votes b
where a.id > b.id
  and a.object_type = b.object_type
  and a.object_id   = b.object_id
  and a.action      = b.action
  and a.voter_id    = b.voter_id;

-- 6) drop the legacy record_key column and its indexes/constraints
alter table public.votes drop constraint if exists votes_record_voter_unique;
alter table public.votes drop constraint if exists votes_record_key_key;
drop index if exists public.votes_record_idx;
alter table public.votes drop column if exists record_key;

-- 7) v2 uniqueness + indexes
alter table public.votes drop constraint if exists votes_object_voter_unique;
alter table public.votes add constraint votes_object_voter_unique
  unique (object_type, object_id, action, voter_id);
create index if not exists votes_object_idx on public.votes (object_type, object_id);
create index if not exists votes_voter_idx   on public.votes (voter_id);

-- 8) privacy shift: anon can no longer SELECT raw votes
alter table public.votes enable row level security;
revoke select on public.votes from anon, authenticated;

create or replace view public.vote_counts as
select object_type, object_id,
       count(*) filter (where action = 'like')    as likes,
       count(*) filter (where action = 'dislike') as dislikes
from public.votes group by object_type, object_id;
grant select on public.vote_counts to anon, authenticated;

commit;
`;
  ensureDir(path.dirname(OUT));
  fs.writeFileSync(OUT, sql);
  console.log(`wrote ${OUT} (${distinct} mappings, ${unmapped.length} unmapped)`);
  return { distinct, unmapped: unmapped.length };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  try {
    generateVoteMigration();
  } catch (e) {
    console.error(e);
    process.exit(1);
  }
}