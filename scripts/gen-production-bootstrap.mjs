// Generates supabase/production_bootstrap.sql — a single, ordered, idempotent
// file that brings a Supabase project fully up to date. Safe to run against
// BOTH a bare project AND a project that still holds the legacy v1 schema —
// which is the state the live project was actually in.
//
// Order (dependency-safe):
//   1. migrations/001...  — votes v1 -> v2 (adds object_type/object_id, backfills
//                           the 169 legacy record_keys, drops record_key).
//                           MUST be first: on a v1 project every later statement
//                           that touches the v2 votes shape would abort.
//   2. schema.sql         — votes/comments/reviews/assets + safe RPCs + views
//   3. migrations/002...  — comments policies, analytics_events, admin_users,
//                           is_admin(), insert_event, admin analytics RPCs
//   4. migrations/003...  — leads & customers + expanded analytics + conversion RPCs
//   5. migrations/004...  — authorize_admin / revoke_admin helpers
//   6. migrations/005...  — grant repair (signature-proof) + RLS audit + authorize
//
// Every step is guarded with IF NOT EXISTS / OR REPLACE / IF EXISTS. No step
// drops a table, truncates data or resets the project.
//
// The email + authorize one-liner stays a manual SQL Editor step by design
// (Monique's email is kept out of the repo).
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(fileURLToPath(import.meta.url), '../../');
const parts = [
  join(root, 'supabase', 'migrations', '001_votes_v2.sql'),
  join(root, 'supabase', 'schema.sql'),
  join(root, 'supabase', 'migrations', '002_comments_analytics_admin.sql'),
  join(root, 'supabase', 'migrations', '003_leads_conversions.sql'),
  join(root, 'supabase', 'migrations', '004_admin_monique.sql'),
  join(root, 'supabase', 'migrations', '005_admin_auth_hardening.sql'),
];

const header = `-- =====================================================================
-- Mika Creator — PRODUCTION BOOTSTRAP (GENERATED BY scripts/gen-production-bootstrap.mjs)
--
-- One-file initialization / upgrade of the Supabase project.
-- Safe + idempotent on a bare project AND on a legacy v1 project.
-- Includes, in order:
--   migrations/001...  votes v1 -> v2 (must run first)
--   schema.sql         votes/comments/reviews/assets + safe RPCs + read views
--   migrations/002...  analytics_events, admin_users, is_admin, admin RPCs
--   migrations/003...  leads, customers, conversion funnel admin RPCs
--   migrations/004...  authorize_admin / revoke_admin helpers
--   migrations/005...  grant repair (signature-proof) + RLS audit + authorize
--
-- It does NOT drop tables, truncate data or reset the project.
--
-- HOW TO APPLY (the ONLY manual step for site schema):
--   Supabase Dashboard -> SQL Editor -> paste this WHOLE file -> Run.
--   If it reports success, the report table at the bottom lists the row counts.
--
--   Then create the admin login (Supabase Dashboard -> Authentication -> Users
--   -> Add User, email mikacreator8@gmail.com, tick "Auto Confirm User"), and
--   grant it admin rights in the SQL Editor:
--     select public.authorize_admin('mikacreator8@gmail.com', 'Monique');
--
--   Then sign in at https://www.mikacreator.co.za/admin/login/
--
-- Do NOT edit this file by hand; edit the source .sql files and re-run:
--   node scripts/gen-production-bootstrap.mjs
-- =====================================================================
`;

const body = parts
  .map((p) => {
    const name = p.split(/[/\\]/).slice(-1)[0];
    return [
      '-- ---------------------------------------------------------------------',
      `-- [source: ${name}]`,
      '-- ---------------------------------------------------------------------',
      readFileSync(p, 'utf8').trimEnd(),
    ].join('\n');
  })
  .join('\n\n\n');

writeFileSync(join(root, 'supabase', 'production_bootstrap.sql'), header + body + '\n');
console.log(`wrote supabase/production_bootstrap.sql (${parts.length} sources)`);