// Generates supabase/production_bootstrap.sql — a single, ordered, idempotent
// file that initializes a BARE production Supabase project.
//
// Order (dependency-safe):
//   1. schema.sql                — votes/comments/reviews/assets + safe RPCs (fresh baseline)
//   2. migrations/002...         — comments analytics + admin_users + is_admin + admin RPCs (needs votes/comments)
//   3. migrations/003...         — leads & customers + expanded analytics + admin conversion RPCs (needs 002)
//   4. migrations/004...         — authorize_admin (Monique) once authorized
//
// 001_votes_v2.sql is deliberately NOT included: it migrates an existing v1
// project (record_key -> ids). A bare project starts from schema.sql instead.
//
// The email + authorize one-liner stays a manual SQL Editor step by design
// (Monique's email is kept out of the repo).
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(fileURLToPath(import.meta.url), '../../');
const parts = [
  join(root, 'supabase', 'schema.sql'),
  join(root, 'supabase', 'migrations', '002_comments_analytics_admin.sql'),
  join(root, 'supabase', 'migrations', '003_leads_conversions.sql'),
  join(root, 'supabase', 'migrations', '004_admin_monique.sql'),
];

const header = `-- =====================================================================
-- Mika Creator — PRODUCTION BOOTSTRAP (GENERATED BY scripts/gen-production-bootstrap.mjs)
--
-- One-file initialization of the production Supabase project (bare DB).
-- Safe + idempotent; includes, in order:
--   schema.sql  (votes/comments/reviews/assets + safe RPCs)
--   migrations/002...  (analytics_events, admin_users, is_admin, admin RPCs)
--   migrations/003...  (leads, customers, conversion funnel admin RPCs)
--   migrations/004...  (authorize_admin helper for Monique)
--
-- HOW TO APPLY (the ONLY manual step for site schema):
--   Supabase Dashboard -> SQL Editor -> paste this WHOLE file -> Run.
--   Then, to grant Monique admin access, run the one-liner:
--     select public.authorize_admin('mikacreator8@gmail.com', 'Monique');
--
-- Do NOT edit this file by hand; edit the source .sql files and re-run:
--   node scripts/gen-production-bootstrap.mjs
-- =====================================================================
`;

const body = parts
  .map((p) => {
    const name = p.split(/[/\\]/).slice(-1)[0];
    return [
      '-- ---------------------------------------------------------------------',
      `-- [source: ${name}]`,
      '-- ---------------------------------------------------------------------',
      readFileSync(p, 'utf8').trimEnd(),
    ].join('\n');
  })
  .join('\n\n\n');

writeFileSync(join(root, 'supabase', 'production_bootstrap.sql'), header + body + '\n');
console.log(`wrote supabase/production_bootstrap.sql (${parts.length} sources)`);